const LANG_KEY = "brxvih.lang";
let currentLang = ["ar", "en"].includes(storageGet(LANG_KEY)) ? storageGet(LANG_KEY) : "ar";

export function getLang() {
  return currentLang;
}

export function isRTL() {
  return currentLang === "ar";
}

export function t(key, vars = {}) {
  const text = translations[currentLang]?.[key] ?? translations.ar[key] ?? key;
  return Object.entries(vars).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    text
  );
}

export function setLang(lang, { silent = false } = {}) {
  if (!["ar", "en"].includes(lang)) return;
  currentLang = lang;
  storageSet(LANG_KEY, lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  applyStaticI18n();
  if (!silent) window.dispatchEvent(new CustomEvent("brxvih:lang", { detail: { lang } }));
}

export function toggleLang() {
  setLang(currentLang === "ar" ? "en" : "ar");
}

export function applyStaticI18n(root = document) {
  qsa("[data-i18n]", root).forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  qsa("[data-i18n-placeholder]", root).forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });
  qsa("[data-i18n-aria-label]", root).forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });
  qsa("[data-i18n-title]", root).forEach((element) => {
    element.setAttribute("title", t(element.dataset.i18nTitle));
  });
}

export function initI18n() {
  setLang(currentLang, { silent: true });
  return currentLang;
}

export function brandLabel(brand) {
  return t(`brand.${brand?.id}`) || brand?.name || "";
}

export function escapeI18n(value) {
  return escapeHtml(value);
}

