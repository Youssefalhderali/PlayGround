let current = (() => {
  try { return localStorage.getItem('brxvih.lang') === 'en' ? 'en' : 'ar' } catch { return 'ar' }
})()

export function getLang() { return current }
export function isRtl() { return current === 'ar' }
export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'ar'
  try { localStorage.setItem('brxvih.lang', current) } catch {}
  document.documentElement.lang = current
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr'
}
export function toggleLang() { setLang(current === 'ar' ? 'en' : 'ar'); return current }
export function t(key, vars = {}) {
  let value = key.split('.').reduce((obj, part) => (obj && obj[part] !== undefined ? obj[part] : undefined), dict[current])
  if (value === undefined) value = key.split('.').reduce((obj, part) => (obj && obj[part] !== undefined ? obj[part] : undefined), dict.ar)
  if (typeof value !== 'string') return key
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''))
}
export function L(obj, base) {
  if (!obj) return ''
  const suffix = current === 'ar' ? 'Ar' : 'En'
  return obj[base + suffix] || obj[base + 'En'] || obj[base + 'Ar'] || obj[base] || ''
}
export function nf(number, options = {}) {
  const locale = current === 'ar' ? 'ar-YE-u-nu-latn' : 'en-US'
  return new Intl.NumberFormat(locale, options).format(Number(number) || 0)
}
export function df(date, options = {}) {
  if (!date) return ''
  const d = new Date(date)
  if (Number.isNaN(d.getTime())) return String(date)
  return new Intl.DateTimeFormat(current === 'ar' ? 'ar-YE-u-nu-latn' : 'en-GB', {
    year: 'numeric', month: 'short', day: 'numeric', ...options
  }).format(d)
}
export function money(value, currency = 'YER') {
  const amount = Number(value)
  if (!Number.isFinite(amount)) return ''
  const decimals = currency === 'YER' ? 0 : 2
  return new Intl.NumberFormat(current === 'ar' ? 'ar-YE-u-nu-latn' : 'en-US', {
    style: 'currency', currency, minimumFractionDigits: decimals, maximumFractionDigits: decimals
  }).format(amount)
}
