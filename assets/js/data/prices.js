export const priceById = Object.fromEntries(prices.map((price) => [price.id, price]));

export const pricesByPhone = (phoneSlug) =>
  prices.filter((price) => price.phoneSlug === phoneSlug);

export const priceRange = (phoneSlug) => {
  const list = pricesByPhone(phoneSlug);
  if (!list.length) return null;
  const amounts = list.map((item) => item.price).filter((value) => typeof value === "number");
  if (!amounts.length) return null;
  return { min: Math.min(...amounts), max: Math.max(...amounts), currency: list[0].currency };
};
